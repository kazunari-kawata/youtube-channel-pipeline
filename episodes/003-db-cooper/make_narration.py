D = "〇一二三四五六七八九"


def k4(n: int) -> str:
    s = ""
    for v, u in ((1000, "千"), (100, "百"), (10, "十")):
        q, n = divmod(n, v)
        if q:
            s += ("" if q == 1 else D[q]) + u
    return s + (D[n] if n else "")


def kanji(n: int) -> str:
    if n == 0:
        return "零"
    man, rest = divmod(n, 10000)
    return (k4(man) + "万" if man else "") + (k4(rest) if rest else "")


def read_of(t: str) -> str:
    t = re.sub(r"\d[\d,]*", lambda m: kanji(int(m.group().replace(",", ""))), t)
    return t.replace("「", "").replace("」", "")


def seg(i, scene, caption, visual, **kw):
    d = {"id": i, "scene": scene}
    if "chapter" in kw:
        d["chapter"] = kw.pop("chapter")
    if "title" in kw:
        d["title"] = kw.pop("title")
    d["caption"] = caption
    d["read"] = read_of(caption)
    d["visual"] = visual
    d.update(kw)
    return d


def ins(scene, var, note):
    return {"kind": "insert", "scene": scene, "var": var, "note": note}


def card(style, text, sub=None, source=None, **kw):
    v = {"kind": "card", "style": style}
    if text:
        v["text"] = text
    if sub:
        v["sub"] = sub
    if source:
        v["source"] = source
    v.update(kw)
    return v


def doc(src, focus, note, ja=None):
    v = {"kind": "doc", "src": src, "focus": focus, "note": note}
    if ja:
        v["ja"] = ja  # 資料に書かれていることの日本語の説明（F-020）。1行目が見出し、2行目から本文
    return v


def photo(src, note, label=None):
    v = {"kind": "photo", "src": src, "note": note}
    if label:
        v["label"] = label
    return v


def mp(view, points, note, route=None):
    v = {"kind": "map", "view": view, "points": points, "note": note}
    if route:
        v["route"] = route
    return v


